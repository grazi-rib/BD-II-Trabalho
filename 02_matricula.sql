USE Universidade;
GO

CREATE PROCEDURE sp_MatriculaAluno
(
    @MATRICULA INT,
    @CURSO CHAR(3),
    @PERLETIVO INT
)
AS
BEGIN
    IF NOT EXISTS (SELECT 1 FROM ALUNOS WHERE MATRICULA = @MATRICULA)
    BEGIN
        RAISERROR('Aluno nao encontrado.', 16, 1);
        RETURN;
    END

    IF NOT EXISTS (SELECT 1 FROM CURSOS WHERE CURSO = @CURSO)
    BEGIN
        RAISERROR('Curso nao encontrado.', 16, 1);
        RETURN;
    END

    INSERT MATRICULA (MATRICULA, CURSO, MATERIA, PROFESSOR, PERLETIVO)
    SELECT @MATRICULA, M.CURSO, M.SIGLA, M.PROFESSOR, @PERLETIVO
    FROM MATERIAS AS M
    WHERE M.CURSO = @CURSO;

    SELECT * FROM MATRICULA WHERE MATRICULA = @MATRICULA;
END
GO

EXEC sp_MatriculaAluno @MATRICULA = 1, @CURSO = 'ENG', @PERLETIVO = 2025;
EXEC sp_MatriculaAluno @MATRICULA = 2, @CURSO = 'ENG', @PERLETIVO = 2025;
EXEC sp_MatriculaAluno @MATRICULA = 3, @CURSO = 'ENG', @PERLETIVO = 2025;
EXEC sp_MatriculaAluno @MATRICULA = 4, @CURSO = 'ENG', @PERLETIVO = 2025;
EXEC sp_MatriculaAluno @MATRICULA = 5, @CURSO = 'ENG', @PERLETIVO = 2025;
GO

SELECT * FROM MATRICULA ORDER BY MATRICULA, MATERIA;